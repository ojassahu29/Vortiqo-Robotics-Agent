from dataclasses import dataclass, field
from typing import Any


@dataclass
class PlanStep:
    """
    One high-level action in a task plan.

    The action and target are determined by the reasoning system.
    Optional destination and parameters provide additional context
    when an action requires them.
    """

    action: str
    target: str
    destination: str | None = None
    parameters: dict[str, Any] = field(default_factory=dict)


@dataclass
class TaskPlan:
    """
    Structured high-level plan generated by the task reasoning layer.
    """

    steps: list[PlanStep] = field(default_factory=list)

    def add_step(self, step: PlanStep) -> None:
        """Add a step to the plan."""
        self.steps.append(step)

    def step_count(self) -> int:
        """Return the number of steps in the plan."""
        return len(self.steps)

    def clear(self) -> None:
        """Remove all plan steps."""
        self.steps.clear()